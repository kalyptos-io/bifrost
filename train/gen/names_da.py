def _load_given_tail() -> tuple[str, ...]:
    # full approved list so given names aren't a memorizable closed set; empty -> GIVEN fallback
    p = Path(__file__).resolve().parent.parent / "data" / "given_names_da.txt"
    if not p.exists():
        return ()
    return tuple(
        ln for ln in p.read_text(encoding="utf-8").splitlines() if ln and not ln.startswith("#")
    )


GIVEN_TAIL = _load_given_tail()
